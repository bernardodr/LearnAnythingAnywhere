package com.laa.llm.structured;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;

import org.springframework.ai.converter.BeanOutputConverter;
import org.springframework.stereotype.Component;

import com.networknt.schema.Error;
import com.networknt.schema.Schema;
import com.networknt.schema.SchemaRegistry;
import com.networknt.schema.SpecificationVersion;

import jakarta.validation.ConstraintViolation;
import jakarta.validation.Validator;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/**
 * JSON schemas for output types (generated by Spring AI from the Java type) and validation of model
 * output against them: JSON parse, then JSON Schema (networknt), then Jakarta constraints on the bound object.
 */
@Component
public class StructuredOutputs {

    public record OutputSchema<T>(Class<T> type, String json, String formatInstructions, Schema validator) {}

    public record Validation<T>(T value, List<String> errors) {
        public boolean ok() {
            return errors.isEmpty();
        }
    }

    private final JsonMapper json;
    private final Validator beanValidator;
    private final SchemaRegistry registry = SchemaRegistry.withDefaultDialect(SpecificationVersion.DRAFT_2020_12);
    private final Map<Class<?>, OutputSchema<?>> schemas = new ConcurrentHashMap<>();

    public StructuredOutputs(JsonMapper json, Validator beanValidator) {
        this.json = json;
        this.beanValidator = beanValidator;
    }

    @SuppressWarnings("unchecked")
    public <T> OutputSchema<T> forType(Class<T> type) {
        return (OutputSchema<T>) schemas.computeIfAbsent(type, t -> {
            var converter = new BeanOutputConverter<>(t, json);
            String schemaJson = converter.getJsonSchema();
            return new OutputSchema<>(t, schemaJson, converter.getFormat(), registry.getSchema(schemaJson));
        });
    }

    public <T> Validation<T> validate(OutputSchema<T> schema, String raw) {
        String text = stripFences(raw);
        JsonNode node;
        try {
            node = json.readTree(text);
        } catch (RuntimeException e) {
            return new Validation<>(null, List.of("Output is not valid JSON: " + firstLine(e.getMessage())));
        }
        List<String> errors = new ArrayList<>();
        for (Error error : schema.validator().validate(node)) {
            String where = String.valueOf(error.getInstanceLocation());
            errors.add((where.isEmpty() ? "$" : where) + ": " + error.getMessage());
        }
        if (!errors.isEmpty()) return new Validation<>(null, errors);

        T value;
        try {
            value = json.treeToValue(node, schema.type());
        } catch (RuntimeException e) {
            return new Validation<>(null, List.of("Output does not bind to " + schema.type().getSimpleName() + ": " + firstLine(e.getMessage())));
        }
        for (ConstraintViolation<T> v : beanValidator.validate(value)) {
            errors.add("$." + v.getPropertyPath() + ": " + v.getMessage());
        }
        return errors.isEmpty() ? new Validation<>(value, List.of()) : new Validation<>(null, errors);
    }

    /** Models sometimes wrap JSON in ```json fences even in JSON mode. */
    static String stripFences(String raw) {
        if (raw == null) return "";
        String s = raw.strip();
        if (s.startsWith("```")) {
            int firstNewline = s.indexOf('\n');
            int lastFence = s.lastIndexOf("```");
            if (firstNewline > 0 && lastFence > firstNewline) s = s.substring(firstNewline + 1, lastFence).strip();
        }
        return s;
    }

    private static String firstLine(String message) {
        if (message == null) return "";
        int nl = message.indexOf('\n');
        return nl < 0 ? message : message.substring(0, nl);
    }
}
